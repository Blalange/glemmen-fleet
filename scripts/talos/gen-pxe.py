#!/usr/bin/env python3
"""Render the iPXE boot script used by the PXE chainloader.

The script matches known Talos nodes by SMBIOS serial, UUID or MAC, boots the
current Talos kernel/initramfs from the asset server and falls through to
netboot.xyz for every other machine.

Usage:
  ./scripts/talos/gen-pxe.py            # write flux/infrastructure/pxe/boot.ipxe
  ./scripts/talos/gen-pxe.py --check    # fail if the committed script is stale
  ./scripts/talos/gen-pxe.py --print    # print the script only
"""

from __future__ import annotations

import argparse
import difflib
import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPT_DIR.parent))

import common  # noqa: E402

SELECTORS_FILE = common.TALOS_DIR / "pxe.yaml"
BOOT_SCRIPT = common.FLUX_DIR / "infrastructure" / "pxe" / "boot.ipxe"

BASE_KERNEL_ARGS = [
    "initrd=initramfs.xz",
    "talos.platform=metal",
    "console=tty0",
    "slab_nomerge",
    "pti=on",
    "consoleblank=0",
    "printk.devkmsg=on",
    "selinux=1",
    "module.sig_enforce=1",
    "proc_mem.force_override=never",
]


def load_selectors() -> dict[str, dict]:
    yaml = common.require_yaml()
    if not SELECTORS_FILE.is_file():
        common.die(f"{SELECTORS_FILE} not found")

    try:
        document = yaml.safe_load(SELECTORS_FILE.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        common.die(f"failed to read {SELECTORS_FILE}: {exc}")

    if not isinstance(document, dict) or not isinstance(document.get("nodes"), dict):
        common.die(f"{SELECTORS_FILE} must contain a 'nodes' mapping")

    selectors: dict[str, dict] = {}
    for name, values in document["nodes"].items():
        if not isinstance(values, dict):
            common.die(f"{SELECTORS_FILE}: node {name!r} must be a mapping")

        serial = values.get("serial")
        uuid = values.get("uuid")
        macs = values.get("macs") or []
        if serial is not None and not isinstance(serial, str):
            common.die(f"{SELECTORS_FILE}: {name}.serial must be a string")
        if uuid is not None and not isinstance(uuid, str):
            common.die(f"{SELECTORS_FILE}: {name}.uuid must be a string")
        if not isinstance(macs, list) or any(
            not isinstance(mac, str) for mac in macs
        ):
            common.die(f"{SELECTORS_FILE}: {name}.macs must be a list of strings")
        if not serial and not uuid and not macs:
            common.die(f"{SELECTORS_FILE}: {name} has no selectors")

        selectors[name] = {
            "serial": serial or "",
            "uuid": uuid or "",
            "macs": macs,
        }

    return selectors


def selector_values(values: dict) -> list[tuple[str, str]]:
    """Return (iPXE variable, literal) pairs, including case variants."""
    pairs: list[tuple[str, str]] = []
    seen: set[tuple[str, str]] = set()

    def add(variable: str, value: str) -> None:
        if not value:
            return
        for variant in (value, value.lower(), value.upper()):
            item = (variable, variant)
            if item not in seen:
                seen.add(item)
                pairs.append(item)

    add("serial", values["serial"])
    add("uuid", values["uuid"])
    add("uuid", values["uuid"].replace("-", ""))
    for mac in values["macs"]:
        add("mac", mac.lower())
        add("mac:hexhyp", mac.lower().replace(":", "-"))
    return pairs


def render() -> str:
    settings = common.load_talos_settings()
    workers = common.worker_names(settings)
    asset_url = settings.get("PXE_ASSET_URL", "").rstrip("/")
    if not asset_url:
        common.die("PXE_ASSET_URL is not set in talos/settings.env")
    selectors = load_selectors()

    node_files = sorted(common.NODES_DIR.glob("*.yaml"))
    if not node_files:
        common.die(f"no node configs found in {common.NODES_DIR}")

    nodes: list[tuple[str, dict, list[str]]] = []
    for node_file in node_files:
        name = node_file.stem
        if name not in selectors:
            common.die(
                f"{name} has no entry in {SELECTORS_FILE} "
                "(add its serial/uuid/macs)"
            )
        network_args = common.maintenance_kernel_args(node_file)
        nodes.append((name, selectors[name], network_args))

    known = {name for name, _, _ in nodes}
    for extra in sorted(set(selectors) - known):
        common.warn(f"{SELECTORS_FILE}: ignoring {extra} (no talos/nodes config)")

    lines: list[str] = [
        "#!ipxe",
        "# Generated by scripts/talos/gen-pxe.py. Do not edit by hand.",
        "#",
        "# Known Talos nodes load the current kernel/initramfs from the asset",
        "# server and then boot their installed Talos system. A node without an",
        "# installation enters maintenance mode. Unknown machines chain",
        "# netboot.xyz.",
        "",
    ]

    for name, values, _ in nodes:
        role = "worker" if name in workers else "control-plane"
        lines.append(f"# {name} ({role})")
        for variable, literal in selector_values(values):
            lines.append(
                f"iseq ${{{variable}}} {literal} && goto talos_{name}"
            )
        lines.append("")

    lines.extend(
        [
            "# No known Talos node matched: fall back to the netboot.xyz menu.",
            "goto netboot",
            "",
        ]
    )

    for name, _, network_args in nodes:
        role = "worker" if name in workers else "control-plane"
        arguments = [*BASE_KERNEL_ARGS, *network_args]
        lines.extend(
            [
                f"# {name} ({role})",
                f":talos_{name}",
                (
                    f"kernel {asset_url}/vmlinuz {' '.join(arguments)} "
                    "|| goto netboot"
                ),
                f"initrd {asset_url}/initramfs.xz || goto netboot",
                "boot || goto netboot",
                "",
            ]
        )

    lines.extend(
        [
            ":netboot",
            "imgfree",
            "echo No Talos profile matched; chainloading netboot.xyz",
            "chain --autofree http://boot.netboot.xyz || shell",
            "",
        ]
    )
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="gen-pxe.py",
        description="Render the iPXE boot script for the PXE chainloader.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if boot.ipxe differs from the generated output",
    )
    parser.add_argument(
        "--print",
        dest="print_only",
        action="store_true",
        help="print the script instead of writing it",
    )
    args = parser.parse_args(argv)

    output = render()

    if args.print_only:
        print(output, end="")
        return 0

    if args.check:
        if not BOOT_SCRIPT.is_file():
            print(f"ERROR: {BOOT_SCRIPT} does not exist", file=sys.stderr)
            return 1
        current = BOOT_SCRIPT.read_text(encoding="utf-8")
        if current != output:
            diff = difflib.unified_diff(
                current.splitlines(),
                output.splitlines(),
                fromfile=str(BOOT_SCRIPT),
                tofile="generated",
                lineterm="",
            )
            print("\n".join(diff), file=sys.stderr)
            print(
                f"ERROR: {BOOT_SCRIPT} is stale "
                "(run ./scripts/talos/gen-pxe.py)",
                file=sys.stderr,
            )
            return 1
        print(f"{BOOT_SCRIPT} is up to date")
        return 0

    BOOT_SCRIPT.parent.mkdir(parents=True, exist_ok=True)
    BOOT_SCRIPT.write_text(output, encoding="utf-8")
    print(f"Wrote {BOOT_SCRIPT} ({len(output.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
